import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '../..')
const catalogPath = path.join(repoRoot, 'gs/data/catalog.go')
const outputPath = path.join(repoRoot, 'web/src/shared/gen2WorldManifest.generated.ts')
const source = fs.readFileSync(catalogPath, 'utf8')
const revision = source.match(/const SourceRevision = "([^"]+)"/)?.[1] || 'unknown'
const pattern = /^\s*0x([0-9a-fA-F]{4}): \{Group: (\d+), Number: (\d+), Name: "([^"]+)", Location: "([^"]*)", WidthBlocks: (\d+), HeightBlocks: (\d+)\},$/gm
const maps = []
let match
while ((match = pattern.exec(source))) {
  maps.push({
    id: Number.parseInt(match[1], 16),
    group: Number(match[2]),
    number: Number(match[3]),
    name: match[4],
    location: match[5],
    width: Number(match[6]) * 2,
    height: Number(match[7]) * 2,
    connections: [],
    pois: []
  })
}
if (!maps.length) throw new Error('no Gen 2 maps parsed from gs/data/catalog.go')
maps.sort((a, b) => a.id - b.id)
const banner = `// Code generated by web/scripts/generate-gen2-world-manifest.mjs; DO NOT EDIT.\n// Source: gs/data/catalog.go generated from pret/pokegold ${revision}. No ROM bytes or graphics are included.\n\n`
fs.writeFileSync(outputPath, banner + `export const GEN2_WORLD_MANIFEST = ${JSON.stringify(maps, null, 2)} as const\n`)
console.log(`generated ${path.relative(repoRoot, outputPath)} (${maps.length} maps)`)
