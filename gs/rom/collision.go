func gen2BlockedDirections() map[uint8]worldmodel.NativeDirectionMask {
	d, u := worldmodel.NativeBlockDown, worldmodel.NativeBlockUp
	l, r := worldmodel.NativeBlockLeft, worldmodel.NativeBlockRight
	base := [8]worldmodel.NativeDirectionMask{r, l, u, d, d | r, d | l, u | r, u | l}
	out := make(map[uint8]worldmodel.NativeDirectionMask, 16)
	for i, mask := range base {
		out[0xb0+uint8(i)] = mask
		out[0xc0+uint8(i)] = mask
	}
	return out
}

func gen2Jumps() []worldmodel.NativeJump {
	d, u := worldmodel.NativeBlockDown, worldmodel.NativeBlockUp
	l, r := worldmodel.NativeBlockLeft, worldmodel.NativeBlockRight
	return []worldmodel.NativeJump{
		{Collision: 0xa0, DirectionMask: r},
		{Collision: 0xa1, DirectionMask: l},
		{Collision: 0xa2, DirectionMask: u},
		{Collision: 0xa3, DirectionMask: d},
		{Collision: 0xa4, DirectionMask: d | r},
		{Collision: 0xa5, DirectionMask: d | l},
		{Collision: 0xa6, DirectionMask: u | r},
		{Collision: 0xa7, DirectionMask: u | l},
	}
}

// Grid decodes one live row-major block buffer into Gen-II walkability.
// Block zero is a sentinel in GetCoordTileCollision and always yields COLL_FF.
func (p *firstBadgeWorldProvider) Grid(mapID uint16, blocks []byte, mode worldmodel.TraversalMode) (worldmodel.NativeGridSpec, error) {
	if p == nil {
		return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: nil first-badge grid provider")
	}
	spec, ok := p.specs[mapID]
	if !ok {
		return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: map %#04x is outside first-badge grid slice", mapID)
	}
	info, ok := gsdata.Map(mapID)
	if !ok {
		return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: generated map %#04x is missing", mapID)
	}
	tileset, ok := firstBadgeTilesetByMapName[spec.name]
	if !ok {
		return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: %s has no first-badge tileset mapping", spec.name)
	}
	table, ok := firstBadgeCollisionTables[tileset]
	if !ok {
		return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: tileset %#02x has no collision table", tileset)
	}
	widthBlocks, heightBlocks := int(info.WidthBlocks), int(info.HeightBlocks)
	if len(blocks) != widthBlocks*heightBlocks {
		return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: %s live blocks length %d, want %d", spec.name, len(blocks), widthBlocks*heightBlocks)
	}
	width, height := widthBlocks*2, heightBlocks*2
	out := worldmodel.NativeGridSpec{
		MapID: mapID, Width: width, Height: height, Traversal: mode,
		Walkable: make([]bool, width*height),
		CollisionTile: make([]uint8, width*height),
		Cuttable: make([]bool, width*height),
		Blocked: gen2BlockedDirections(),
		Jumps: gen2Jumps(),
	}
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			block := blocks[(y/2)*widthBlocks+x/2]
			collision := uint8(0xff)
			if block != 0 {
				index := int(block)*4 + (x & 1) + 2*(y&1)
				if index >= len(table) {
					return worldmodel.NativeGridSpec{}, fmt.Errorf("gs/rom: %s block %#02x collision index %d exceeds tileset %#02x table length %d", spec.name, block, index, tileset, len(table))
				}
				collision = table[index]
			}
			i := y*width+x
			out.CollisionTile[i] = collision
			permission := gen2CollisionPermission[collision] & 0x0f
			out.Walkable[i] = permission == 0 || (mode == worldmodel.TraversalWater && permission == 1)
			out.Cuttable[i] = collision == 0x12 || collision == 0x1a
		}
	}
	return out, nil
}
